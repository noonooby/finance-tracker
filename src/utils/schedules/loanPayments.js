import { server } from '../server';
import { predictNextDate, formatCurrency, localDate, generateId } from '../helpers';
import { recordLoanPayment, reverseTransaction } from '../money';
import { logActivity } from '../activityLogger';

/**
 * Loan Payment Management
 * Every payment is one server step (both balances, the payment row, the transaction and the loan's next date),
 * keyed loan-payment:<loanId>:<dueDate> so a due date is paid at most once.
 */

const newTxId = () => (typeof crypto !== 'undefined' && crypto.randomUUID ? crypto.randomUUID() : generateId());
const round2 = (n) => Math.round(Number(n) * 100) / 100;
const dayOf = (iso) => (iso ? Number(String(iso).split('T')[0].split('-')[2]) || undefined : undefined);

async function freshAccounts() {
  const [b, c, l] = await Promise.all([
    server.from('bank_accounts').select('*'),
    server.from('credit_cards').select('*'),
    server.from('loans').select('*'),
  ]);
  return { bankAccounts: b.data || [], creditCards: c.data || [], loans: l.data || [] };
}

/**
 * Pay every due date up to today for each loan with a connected payment source.
 * Stops a loan at its first refusal (for example not enough money) and reports it.
 * The arguments are kept for callers; balances are read fresh from the server.
 */
// eslint-disable-next-line no-unused-vars
export async function processOverdueLoanPayments(loans, creditCards = [], bankAccounts = []) {
  const todayString = localDate();
  const results = { processed: [], failed: [], skipped: [] };
  // Nothing due in the list just loaded: no need to read the balances again.
  if (!(loans || []).some((l) => (l.connected_payment_source || l.on_card_id) && l.next_payment_date && String(l.next_payment_date).split('T')[0] <= todayString)) return results;
  const accounts = await freshAccounts();

  const ids = new Set((loans || []).map((l) => String(l.id)));
  const due = accounts.loans.filter((l) => ids.has(String(l.id)) && l.next_payment_date && String(l.next_payment_date).split('T')[0] <= todayString);

  for (const start of due) {
    let loan = start;
    const configured = round2(Number(loan.payment_amount) || 0);
    if (configured <= 0) {
      results.skipped.push({ loan: loan.name, reason: 'No payment amount configured' });
      continue;
    }
    // A plan inside a credit card (equal payment plan): its balance is already part of the card's balance, so a due date
    // moves no money. The installment is billed to the card, and the plan's remaining balance goes down by it.
    // Each step is guarded by the date it expects, so running this twice changes nothing.
    if (loan.on_card_id) {
      let dueDate = String(loan.next_payment_date).split('T')[0];
      let left = round2(Number(loan.balance) || 0);
      const anchor = dayOf(loan.start_date) || dayOf(loan.next_payment_date);
      while (dueDate <= todayString && left > 0) {
        const nextDate = predictNextDate(dueDate, loan.frequency || 'monthly', anchor);
        const bill = Math.min(configured, left);
        const { data } = await server.from('loans').update({ balance: round2(left - bill), next_payment_date: nextDate, last_billed: dueDate })
          .eq('id', loan.id).eq('next_payment_date', loan.next_payment_date).select();
        if (!data || !data.length) break;
        loan = data[0];
        left = round2(left - bill);
        results.processed.push({ loan: loan.name, amount: bill, dueDate, billedToCard: true });
        dueDate = nextDate;
      }
      continue;
    }
    const sourceType = loan.connected_payment_source;
    // An old source with no account (cash before it was an account) counts as none.
    if (!sourceType || !loan.connected_payment_source_id) {
      results.skipped.push({ loan: loan.name, reason: 'No connected payment source' });
      continue;
    }
    const anchorDay = dayOf(loan.start_date) || dayOf(loan.next_payment_date);
    let dueDate = String(loan.next_payment_date).split('T')[0];

    while (dueDate <= todayString) {
      const owed = round2(Number(loan.balance) || 0);
      if (owed <= 0) {
        results.skipped.push({ loan: loan.name, reason: 'Loan is paid off' });
        break;
      }
      const amount = Math.min(configured, owed);
      const nextDate = predictNextDate(dueDate, loan.frequency || 'monthly', anchorDay);
      const result = await createLoanPayment({
        loanId: loan.id,
        amount,
        paymentDate: dueDate,
        dueDate,
        nextDate,
        paymentSource: sourceType,
        paymentSourceId: loan.connected_payment_source_id,
        autoGenerated: true,
      }, loan, null, accounts);

      if (!result.success) {
        results.failed.push({ loan: loan.name, dueDate, reason: result.error || 'Processing failed' });
        break;
      }
      if (result.repeated) {
        await server.from('loans').update({ next_payment_date: nextDate }).eq('id', loan.id).eq('next_payment_date', dueDate);
      } else {
        results.processed.push({ loan: loan.name, amount, dueDate, source: result.sourceName, sourceType });
        loan = { ...loan, balance: round2(owed - amount), recurring_occurrences_completed: (loan.recurring_occurrences_completed || 0) + 1 };
      }
      dueDate = nextDate;
    }
  }
  return results;
}

/**
 * Pay a loan once. paymentData: { loanId, amount, paymentDate, dueDate, nextDate?, paymentSource, paymentSourceId, autoGenerated }.
 * accounts (optional) = { bankAccounts, creditCards, loans }; read fresh when not given.
 * Returns { success, payment, repeated } or { success: false, error }.
 */
// eslint-disable-next-line no-unused-vars
export async function createLoanPayment(paymentData, loan, paymentSource, accounts) {
  try {
    const acc = accounts || (await freshAccounts());
    const current = acc.loans.find((l) => String(l.id) === String(loan.id)) || loan;
    const amount = round2(Number(paymentData.amount) || 0);
    const balanceBefore = round2(Number(current.balance) || 0);
    const balanceAfter = round2(balanceBefore - amount);
    const source = `${paymentData.paymentSource}:${paymentData.paymentSourceId}`;
    const list = paymentData.paymentSource === 'bank_account' ? acc.bankAccounts : acc.creditCards;
    const sourceName = (list.find((x) => String(x.id) === String(paymentData.paymentSourceId)) || {}).name || paymentData.paymentSourceName;
    const dueDate = paymentData.dueDate || current.next_payment_date;
    const nextDate = paymentData.nextDate || predictNextDate(String(dueDate).split('T')[0], current.frequency || 'monthly', dayOf(current.start_date));
    const txId = newTxId();

    const r = await recordLoanPayment({
      loanId: current.id,
      amount,
      source,
      date: paymentData.paymentDate,
      description: `Loan payment for ${current.name} from ${sourceName}`,
      key: `loan-payment:${current.id}:${String(dueDate).split('T')[0]}`,
      extra: { id: txId, category_id: 'loan_payment', category_name: 'Loan Payment', auto_generated: !!paymentData.autoGenerated },
      paymentRow: {
        due_date: dueDate,
        payment_source: paymentData.paymentSource,
        payment_source_id: paymentData.paymentSourceId || null,
        payment_source_name: sourceName,
        status: 'completed',
        auto_generated: !!paymentData.autoGenerated,
        balance_before: balanceBefore,
        balance_after: balanceAfter,
        transaction_id: txId,
      },
      updates: [{ table: 'loans', id: current.id, values: {
        last_payment_date: paymentData.paymentDate,
        ...(paymentData.autoGenerated ? { last_auto_payment_date: paymentData.paymentDate } : {}),
        next_payment_date: nextDate,
        recurring_occurrences_completed: (current.recurring_occurrences_completed || 0) + 1,
      } }],
    }, { ...acc, loans: [current] });
    if (r.repeated) return { success: true, repeated: true };

    const paymentRecord = (r.rows || []).find((x) => x.loan_id === current.id && !x.type) || null;
    await logActivity(
      'loan_payment', 'loan', current.id, current.name,
      `Loan payment: ${formatCurrency(amount)} for ${current.name} from ${sourceName} - Balance ${formatCurrency(balanceBefore)} -> ${formatCurrency(balanceAfter)}`,
      { paymentId: paymentRecord && paymentRecord.id, transactionId: txId, amount, paymentSource: paymentData.paymentSource,
        paymentSourceId: paymentData.paymentSourceId, paymentSourceName: sourceName, balanceBefore, balanceAfter }
    );
    return { success: true, payment: paymentRecord, sourceName };
  } catch (error) {
    console.error('Error creating loan payment:', error);
    return { success: false, error: error.message };
  }
}

/**
 * Get loan payment history
 */
export async function getLoanPaymentHistory(loanId) {
  try {
    const { data, error } = await server
      .from('loan_payments')
      .select('*')
      .eq('loan_id', loanId)
      .order('payment_date', { ascending: false });
    if (error) throw error;
    return data || [];
  } catch (error) {
    console.error('Error fetching loan payment history:', error);
    return [];
  }
}

/**
 * Undo a loan payment: reverses its transaction exactly, then rolls the loan's next date back.
 */
export async function undoLoanPayment(paymentId) {
  const { data: payment, error: fetchError } = await server.from('loan_payments').select('*').eq('id', paymentId).single();
  if (fetchError) throw fetchError;
  if (!payment) throw new Error('Payment not found');
  if (payment.status === 'undone') return true;
  if (!payment.transaction_id) throw new Error('This payment has no linked transaction to undo.');

  await reverseTransaction(payment.transaction_id);

  const { data: loan } = await server.from('loans').select('*').eq('id', payment.loan_id).single();
  if (loan) {
    await server.from('loans').update({
      next_payment_date: payment.due_date,
      recurring_occurrences_completed: Math.max(0, (loan.recurring_occurrences_completed || 0) - 1),
    }).eq('id', loan.id);
  }
  await server.from('loan_payments').update({ status: 'undone', undone_at: new Date().toISOString() }).eq('id', paymentId);
  return true;
}
