import { supabase } from '../supabase';
import { formatCurrency, localDate, addMonths, generateId } from '../helpers';
import { recordCardPayment, reverseTransaction } from '../money';
import { logActivity } from '../activityLogger';

/**
 * Credit Card Payment Management
 * Every payment is one server step (both balances, the payment row, the transaction and the card's next due date),
 * keyed card-payment:<cardId>:<dueDate> so a due date is paid at most once.
 */

const newTxId = () => (typeof crypto !== 'undefined' && crypto.randomUUID ? crypto.randomUUID() : generateId());
const round2 = (n) => Math.round(Number(n) * 100) / 100;
const dayOf = (iso) => (iso ? Number(String(iso).split('T')[0].split('-')[2]) || undefined : undefined);
const parseLocal = (iso) => {
  const [y, m, d] = String(iso).split('T')[0].split('-').map(Number);
  return new Date(y, m - 1, d);
};
const nextDue = (iso, anchorDay) => localDate(addMonths(parseLocal(iso), 1, anchorDay || dayOf(iso)));

// The amount set for automatic payment, if the card has one; otherwise null (pay the full balance).
const configuredAmount = (card) => {
  for (const f of ['auto_pay_amount', 'autopay_amount', 'payment_amount', 'minimum_payment', 'min_payment']) {
    const n = round2(Number(card[f]) || 0);
    if (n > 0) return n;
  }
  return null;
};

async function freshAccounts() {
  const [b, c] = await Promise.all([
    supabase.from('bank_accounts').select('*'),
    supabase.from('credit_cards').select('*'),
  ]);
  return { bankAccounts: b.data || [], creditCards: c.data || [] };
}

/**
 * Pay every due date up to today for each card with a connected payment source.
 * Pays the card's set amount when it has one, otherwise the full balance, never more than is owed.
 * Stops a card at its first refusal (for example not enough money) and reports it.
 * The arguments are kept for callers; balances are read fresh from the server.
 */
// eslint-disable-next-line no-unused-vars
export async function processOverdueCreditCardPayments(creditCards, bankAccounts = [], cashInHand = 0) {
  const todayString = localDate();
  const results = { processed: [], failed: [], skipped: [] };
  const accounts = await freshAccounts();

  const ids = new Set((creditCards || []).map((c) => String(c.id)));
  const due = accounts.creditCards.filter((c) => ids.has(String(c.id)) && !c.is_gift_card && c.due_date
    && String(c.due_date).split('T')[0] <= todayString && (Number(c.balance) || 0) > 0);

  for (const start of due) {
    let card = start;
    const sourceType = card.connected_payment_source;
    if (!sourceType || (sourceType !== 'cash_in_hand' && !card.connected_payment_source_id)) {
      results.skipped.push({ card: card.name, reason: 'No connected payment source' });
      continue;
    }
    const anchorDay = dayOf(card.due_date);
    let dueDate = String(card.due_date).split('T')[0];

    while (dueDate <= todayString) {
      const owed = round2(Number(card.balance) || 0);
      const nextDate = nextDue(dueDate, anchorDay);
      if (owed <= 0) {
        // Nothing owed for this period: just move to the next due date.
        await supabase.from('credit_cards').update({ due_date: nextDate }).eq('id', card.id).eq('due_date', dueDate);
        dueDate = nextDate;
        continue;
      }
      const amount = Math.min(configuredAmount(card) || owed, owed);
      const result = await createCreditCardPayment({
        cardId: card.id,
        amount,
        paymentDate: dueDate,
        dueDate,
        nextDate,
        paymentSource: sourceType,
        paymentSourceId: card.connected_payment_source_id,
        autoGenerated: true,
      }, card, null, accounts);

      if (!result.success) {
        results.failed.push({ card: card.name, dueDate, reason: result.error || 'Processing failed' });
        break;
      }
      if (result.repeated) {
        await supabase.from('credit_cards').update({ due_date: nextDate }).eq('id', card.id).eq('due_date', dueDate);
      } else {
        results.processed.push({ card: card.name, amount, dueDate, source: result.sourceName, sourceType });
        card = { ...card, balance: round2(owed - amount) };
      }
      dueDate = nextDate;
    }
  }
  return results;
}

/**
 * Pay a card once. paymentData: { cardId, amount, paymentDate, dueDate, nextDate?, paymentSource, paymentSourceId, autoGenerated }.
 * accounts (optional) = { bankAccounts, creditCards }; read fresh when not given.
 * Returns { success, payment, repeated } or { success: false, error }.
 */
// eslint-disable-next-line no-unused-vars
export async function createCreditCardPayment(paymentData, card, paymentSource, accounts) {
  try {
    const acc = accounts || (await freshAccounts());
    const current = acc.creditCards.find((c) => String(c.id) === String(card.id)) || card;
    const amount = round2(Number(paymentData.amount) || 0);
    const balanceBefore = round2(Number(current.balance) || 0);
    const balanceAfter = round2(balanceBefore - amount);
    const source = paymentData.paymentSource === 'cash_in_hand' ? 'cash_in_hand' : `${paymentData.paymentSource}:${paymentData.paymentSourceId}`;
    const sourceName = paymentData.paymentSource === 'cash_in_hand' ? 'Cash in Hand'
      : (acc.bankAccounts.find((x) => String(x.id) === String(paymentData.paymentSourceId)) || {}).name || paymentData.paymentSourceName;
    const dueDate = String(paymentData.dueDate || current.due_date).split('T')[0];
    const nextDate = paymentData.nextDate || nextDue(dueDate);
    const txId = newTxId();

    const r = await recordCardPayment({
      cardId: current.id,
      amount,
      source,
      date: paymentData.paymentDate,
      description: `Credit card payment for ${current.name} from ${sourceName}`,
      key: `card-payment:${current.id}:${dueDate}`,
      extra: { id: txId, category_id: 'credit_card_payment', category_name: 'Credit Card Payment', auto_generated: !!paymentData.autoGenerated },
      paymentRow: {
        due_date: dueDate,
        payment_source: paymentData.paymentSource,
        payment_source_id: paymentData.paymentSourceId || null,
        payment_source_name: sourceName,
        status: 'completed',
        auto_generated: !!paymentData.autoGenerated,
        balance_before: balanceBefore,
        balance_after: balanceAfter,
        transaction_id: txId,
      },
      updates: [{ table: 'credit_cards', id: current.id, values: {
        last_payment_date: paymentData.paymentDate,
        ...(paymentData.autoGenerated ? { last_auto_payment_date: paymentData.paymentDate } : {}),
        last_payment_amount: amount,
        due_date: nextDate,
      } }],
    }, acc);
    if (r.repeated) return { success: true, repeated: true };

    const paymentRecord = (r.rows || []).find((x) => !x.type && String(x.card_id) === String(current.id)) || null;
    await logActivity(
      'credit_card_payment', 'card', current.id, current.name,
      `Credit card payment: ${formatCurrency(amount)} for ${current.name} from ${sourceName} - Balance ${formatCurrency(balanceBefore)} -> ${formatCurrency(balanceAfter)}`,
      { paymentId: paymentRecord && paymentRecord.id, transactionId: txId, amount, paymentSource: paymentData.paymentSource,
        paymentSourceId: paymentData.paymentSourceId, paymentSourceName: sourceName, balanceBefore, balanceAfter }
    );
    return { success: true, payment: paymentRecord, sourceName };
  } catch (error) {
    console.error('Error creating credit card payment:', error);
    return { success: false, error: error.message };
  }
}

/**
 * Get credit card payment history
 */
export async function getCreditCardPaymentHistory(cardId) {
  try {
    const { data, error } = await supabase
      .from('credit_card_payments')
      .select('*')
      .eq('card_id', cardId)
      .order('payment_date', { ascending: false });
    if (error) throw error;
    return data || [];
  } catch (error) {
    console.error('Error fetching credit card payment history:', error);
    return [];
  }
}

/**
 * Undo a credit card payment: reverses its transaction exactly, then puts the card's due date back.
 */
export async function undoCreditCardPayment(paymentId) {
  const { data: payment, error: fetchError } = await supabase.from('credit_card_payments').select('*').eq('id', paymentId).single();
  if (fetchError) throw fetchError;
  if (!payment) throw new Error('Payment not found');
  if (payment.status === 'undone') return true;
  if (!payment.transaction_id) throw new Error('This payment has no linked transaction to undo.');

  await reverseTransaction(payment.transaction_id);

  if (payment.due_date) {
    await supabase.from('credit_cards').update({ due_date: String(payment.due_date).split('T')[0] }).eq('id', payment.card_id);
  }
  await supabase.from('credit_card_payments').update({ status: 'undone', undone_at: new Date().toISOString() }).eq('id', paymentId);
  return true;
}
